-- Описание поста: третье текстовое поле рядом с заголовком и подзаголовком.
--
-- Заголовок — основная мысль одной строкой, подзаголовок — детали одной
-- строкой, описание — длинный текст: черновик подписи, заметки, список
-- кадров. Разные они потому, что в сетке показываются **по отдельности**:
-- подзаголовок удобен, когда проверяешь состав, описание — когда пишешь.
--
-- `not null default ''` ровно как у подзаголовка: пустая строка и есть
-- «не заполнено», и отдельного значения для этого не нужно.

alter table public.posts
  add column if not exists description text not null default '';
