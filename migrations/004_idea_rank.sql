-- Идеям нужен свой порядок.
--
-- `posts_idea_is_bare` запрещало идее всё разом: и дни, и ранг. Дни запрещены
-- по делу — у идеи нет места в очереди, значит нет и дня, который это место
-- дало бы. А вот **порядок у полки идей есть**: именно там его переставляют
-- чаще всего, потому что полка и есть то, что ещё не разложено.
--
-- Ранг после этого значит «место в своём списке», а не «место в очереди»:
-- у запланированного это очередь, у идеи — полка. Списки разные и сортируются
-- порознь, поэтому одинаковые числа в них друг другу не мешают.

alter table public.posts
  drop constraint if exists posts_idea_is_bare;

alter table public.posts
  add constraint posts_idea_has_no_days check (
    status <> 'idea' or (published_on is null and target_on is null)
  );
