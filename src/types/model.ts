/**
 * Форма данных доски в памяти. Всё остальное импортирует типы отсюда.
 *
 * Четыре сущности: серия, пост, сторис, актуальное. Правила, по которым они
 * сочетаются, — в `docs/wiki/`, определения слов — в `CONTEXT.md`.
 *
 * Комментарии к полям объясняют, **что значит отсутствующее поле**: почти
 * везде `null` здесь — это ответ, а не пропуск.
 */

/** Что это за объект. Ровно один, третьего не бывает. */
export type Format = "reel" | "single" | "carousel"

/** Можно ли ещё двигать. Архив — не состояние, а отдельный флаг. */
export type Status = "posted" | "planned" | "idea"

/** Конечную серию доводят до финала, рубрику подсыпают между плотными кусками. */
export type SeriesKind = "finite" | "rubric"

/** Зачем сторис. Необязательна. */
export type StoryRole = "teaser" | "pointer" | "behind"

/**
 * Серия — замысел, который держит посты вместе, или сюжет внутри неё.
 * Уровней ровно два: у сюжета `parentId` заполнен, и тогда цвет и вид он
 * берёт у родителя, а своих не имеет. База проверяет это триггером.
 */
export type Series = {
  id: string
  /** `null` — это серия верхнего уровня; иначе это сюжет внутри неё. */
  parentId: string | null
  name: string
  /** Есть только у верхнего уровня: цвет в сетке берётся с него. */
  color: string | null
  /** Есть только у верхнего уровня. */
  kind: SeriesKind | null
}

/**
 * Пост — одна единица в ленте профиля.
 *
 * Про даты: `publishedOn` — настоящий день выхода, `targetOn` — ориентир,
 * который ничем не управляет и переживает публикацию, чтобы «собирался 10-го,
 * вышло 12-го» осталось видно. Последовательностью запланированного
 * распоряжается только `rank`.
 */
export type Post = {
  id: string
  /** `null` — «вне серий»: у поста нет замысла за ним, и это ответ. */
  seriesId: string | null
  format: Format
  status: Status
  /** Убран с глаз. Ортогонален состоянию: архивный пост всё равно опубликован. */
  archived: boolean
  /** Заполнен только у опубликованного. */
  publishedOn: string | null
  /** Ориентир. `null` — пост просто стоит в очереди и дня у него нет. */
  targetOn: string | null
  /** Место в очереди. Есть только у запланированного. См. `lib/rank.ts`. */
  rank: number | null
  heading: string
  /** Детали одной строкой. */
  subheading: string
  /** Длинный текст: черновик подписи, заметки, список кадров. */
  description: string
  tags: string[]
  /** Путь в хранилище. `null` — обложка ещё не выбрана. */
  coverPath: string | null
}

/**
 * Сторис — один выпуск, связка слайдов на одну мысль, а не отдельный слайд.
 *
 * Два независимых признака: к чему привязана и зачем она. Заполнена не больше
 * одной привязки; обе пустые — «сама по себе».
 */
export type Story = {
  id: string
  /** Привязка к посту. */
  attachPostId: string | null
  /** Привязка к серии: закулисье относится ко всей поездке, а не к одному дню. */
  attachSeriesId: string | null
  /** `null` — роль не указана, и выдумывать её не надо. */
  role: StoryRole | null
  /** Свой день. `null` — он выводится из поста по роли при чтении. */
  onDate: string | null
  body: string
}

/**
 * Актуальное — постоянный набор сторис в профиле. Не серия: «Обо мне» серии
 * не имеет вовсе, «Еда» пересекает несколько.
 */
export type Highlight = {
  id: string
  /** `null` — актуальное не отвечает ни одной серии, и это нормально. */
  seriesId: string | null
  name: string
  coverPath: string | null
  /** `false` — задумано, но ещё не собрано в профиле. */
  assembled: boolean
  /** Порядок массива — это порядок проигрывания. */
  storyIds: string[]
}

/** Всё, что доска прочитала за одного владельца. */
export type Board = {
  series: Series[]
  posts: Post[]
  stories: Story[]
  highlights: Highlight[]
}

export const EMPTY_BOARD: Board = { series: [], posts: [], stories: [], highlights: [] }
