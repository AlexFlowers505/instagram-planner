/**
 * Цвета для новых серий.
 *
 * Сам цвет — **данные пользователя**: он хранится hex-ом на серии и никогда не
 * перекрашивается под интерфейс. Здесь только набор, из которого выбирают,
 * когда серию заводят. Поэтому это и не нарушает запрет на hex в компонентах:
 * литералы живут в одном месте, а не разбросаны по разметке.
 *
 * Выбраны так, чтобы отличаться друг от друга при 4:5 и тонкой рейке, и чтобы
 * оттенок заглушки оставался читаемым и на светлом, и на тёмном.
 */
export const SERIES_PALETTE = [
  "#B8422F", // кирпичный
  "#3E7C8C", // приглушённый бирюзовый
  "#7D6AA8", // фиолетовый
  "#6E8B4A", // оливковый
  "#C08A3E", // охра
  "#8C5A7A", // сливовый
  "#4A6FA5", // синий
  "#8C949E", // серый
] as const

/** Цвет для новой серии: первый, который ещё не занят, иначе по кругу. */
export function nextColor(used: ReadonlyArray<string | null>): string {
  const taken = new Set(used.filter(Boolean) as string[])
  return SERIES_PALETTE.find(c => !taken.has(c)) ?? SERIES_PALETTE[taken.size % SERIES_PALETTE.length]
}
